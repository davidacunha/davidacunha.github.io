function setText(key, value) {
  document.querySelectorAll(`[data-i18n="${key}"]`).forEach(el => { el.textContent = value; });
}

function renderRoles(containerId, roles) {
  const container = document.getElementById(containerId);
  container.innerHTML = "";
  roles.forEach(role => {
    const hasBullets = role.bullets && role.bullets.length > 0;
    const div = document.createElement("div");
    div.className = "role";
    const bulletsHtml = hasBullets
      ? `<ul>${role.bullets.map(b => `<li>${b}</li>`).join("")}</ul>`
      : "";
    div.innerHTML = `
      <div class="role-head${hasBullets ? " toggleable" : ""}"${hasBullets ? ' role="button" tabindex="0" aria-expanded="true"' : ""}>
        <span class="role-title-wrap">
          ${hasBullets ? '<span class="role-chevron">▾</span>' : ""}
          <span class="role-title">${role.title}</span>
        </span>
        <span class="role-dates">${role.dates}</span>
      </div>
      ${bulletsHtml}
    `;
    if (hasBullets) {
      const head = div.querySelector(".role-head");
      const toggle = () => {
        const collapsed = div.classList.toggle("collapsed");
        head.setAttribute("aria-expanded", String(!collapsed));
      };
      head.addEventListener("click", toggle);
      head.addEventListener("keydown", e => {
        if (e.key === "Enter" || e.key === " ") { e.preventDefault(); toggle(); }
      });
    }
    container.appendChild(div);
  });
}

function render(lang) {
  const t = I18N[lang];

  setText("header.title", t.header.title);
  setText("header.location", t.header.location);
  setText("labels.summary", t.labels.summary);
  setText("labels.experience", t.labels.experience);
  setText("labels.education", t.labels.education);
  setText("labels.languages", t.labels.languages);
  setText("labels.skills", t.labels.skills);
  setText("summary", t.summary);
  setText("education.degree", t.education.degree);
  setText("education.dates", t.education.dates);

  renderRoles("crmbonus-roles", t.crmbonus);
  renderRoles("britania-roles", t.britania);

  const skillsList = document.getElementById("skills-list");
  skillsList.innerHTML = t.skills.map(s => `<li>${s}</li>`).join("");

  const langList = document.getElementById("lang-list");
  langList.innerHTML = t.languages.map(l => `<li><span>${l.name}</span><span>${l.level}</span></li>`).join("");

  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  try { localStorage.setItem("resume-lang", lang); } catch (e) {}
}

function detectDefaultLang() {
  try {
    const saved = localStorage.getItem("resume-lang");
    if (saved && I18N[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.language || "pt").toLowerCase();
  if (nav.startsWith("en")) return "en";
  if (nav.startsWith("es")) return "es";
  return "pt";
}

document.querySelectorAll(".lang-btn").forEach(btn => {
  btn.addEventListener("click", () => render(btn.dataset.lang));
});

render(detectDefaultLang());

/* Theme toggle */
const themeToggle = document.getElementById("theme-toggle");
const systemDark = window.matchMedia("(prefers-color-scheme: dark)");

function currentTheme() {
  const explicit = document.documentElement.getAttribute("data-theme");
  if (explicit) return explicit;
  return systemDark.matches ? "dark" : "light";
}

function updateToggleIcon() {
  themeToggle.textContent = currentTheme() === "dark" ? "☀️" : "🌙";
}

function applyTheme(theme, persist) {
  document.documentElement.setAttribute("data-theme", theme);
  if (persist) {
    try { localStorage.setItem("theme-pref", theme); } catch (e) {}
  }
  updateToggleIcon();
}

(function initTheme() {
  let saved = null;
  try { saved = localStorage.getItem("theme-pref"); } catch (e) {}
  if (saved === "light" || saved === "dark") {
    applyTheme(saved, false);
  } else {
    updateToggleIcon();
  }
})();

themeToggle.addEventListener("click", () => {
  applyTheme(currentTheme() === "dark" ? "light" : "dark", true);
});

systemDark.addEventListener("change", () => {
  let saved = null;
  try { saved = localStorage.getItem("theme-pref"); } catch (e) {}
  if (!saved) updateToggleIcon();
});
